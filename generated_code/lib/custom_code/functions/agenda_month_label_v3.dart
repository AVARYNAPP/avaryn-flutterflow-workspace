/// Formats the agenda month in natural Dutch.
String? agendaMonthLabelV3(DateTime? month) {
  final value = month ?? DateTime.now();
  const months = <String>[
    'januari',
    'februari',
    'maart',
    'april',
    'mei',
    'juni',
    'juli',
    'augustus',
    'september',
    'oktober',
    'november',
    'december',
  ];
  return '${months[value.month - 1]} ${value.year}';
}
