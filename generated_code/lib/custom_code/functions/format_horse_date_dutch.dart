/// Formats an optional horse date in natural Dutch, for example 17 april
/// 2015.
String? formatHorseDateDutch(DateTime? date) {
  if (date == null) return '';
  const months = <String>[
    'januari',
    'februari',
    'maart',
    'april',
    'mei',
    'juni',
    'juli',
    'augustus',
    'september',
    'oktober',
    'november',
    'december',
  ];
  return '${date.day} ${months[date.month - 1]} ${date.year}';
}
