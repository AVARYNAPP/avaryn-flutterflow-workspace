/// Formats an optional activity time, using a clear Dutch empty label.
String? formatActivityTimeDutch(DateTime? time) {
  if (time == null) return 'Geen tijd';
  final hour = time.hour.toString().padLeft(2, '0');
  final minute = time.minute.toString().padLeft(2, '0');
  return '$hour:$minute';
}
